#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '..');
const webRequire = createRequire(path.join(root, 'apps/web/package.json'));
const ts = webRequire('typescript');
const source = fs.readFileSync(path.join(root, 'apps/web/src/lib/auth-navigation.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const output = { exports: {} };
new Function('module', 'exports', compiled)(output, output.exports);
const { safeAuthRedirect, authPageHref, afterAuthentication, cartHref, accountOrders } = output.exports;
const pkg = 'aaaaaaaaaaaaaaaaaaaaaaaa', student = 'bbbbbbbbbbbbbbbbbbbbbbbb';
let checks = 0;
function equal(actual, expected) { assert.equal(actual, expected); checks += 1; }
for (const url of ['https://evil.test', '//evil.test', '/\\evil.test', '/%2f%2fevil.test', '/cart%5cfoo', 'javascript:alert(1)', '/cart\n', '/cart%00', '/login?redirect=/cart', '/register', '/account/security/other', '/cart#https://evil.test']) equal(safeAuthRedirect(url), null);
equal(cartHref(pkg, student), `/cart?packageId=${pkg}&studentId=${student}`);
equal(cartHref('https://evil.test'), '/cart');
equal(safeAuthRedirect(`/cart?packageId=${pkg}&price=0.01&redirect=https://evil.test`), `/cart?packageId=${pkg}`);
equal(safeAuthRedirect(`/cart?packageId=invalid`), null);
equal(safeAuthRedirect(`/cart?packageId=${pkg}&studentId=invalid`), null);
equal(safeAuthRedirect(`/payment?packageId=${pkg}`), `/cart?packageId=${pkg}`);
equal(safeAuthRedirect(`/payment/result?orderId=${pkg}&status=success`), `/payment/result?orderId=${pkg}`);
equal(safeAuthRedirect('/payment/result'), '/payment/result');
equal(safeAuthRedirect(`/packages/${pkg}`), `/packages/${pkg}`);
equal(safeAuthRedirect('/packages/not-an-id'), null);
equal(safeAuthRedirect('/admin/orders', 'STUDENT'), null);
equal(safeAuthRedirect('/student2', 'STUDENT'), null);
equal(safeAuthRedirect('/student/../../admin', 'STUDENT'), null);
equal(safeAuthRedirect('/student/packages', 'STUDENT'), '/student/packages');
equal(safeAuthRedirect('/admin/orders', 'SUPERADMIN'), '/admin/orders');
equal(afterAuthentication('PARENT', `/cart?packageId=${pkg}`), `/cart?packageId=${pkg}`);
equal(afterAuthentication('STUDENT', '//evil.test'), '/student');
equal(afterAuthentication('TEACHER', '/admin/orders'), '/teacher');
equal(authPageHref('register', `/cart?packageId=${pkg}`), `/register?redirect=${encodeURIComponent(`/cart?packageId=${pkg}`)}`);
equal(authPageHref('login', 'https://evil.test'), '/login');
equal(accountOrders('ADMIN'), '/admin/orders'); equal(accountOrders('PARENT'), '/parent/packages'); equal(accountOrders('STUDENT'), '/student/packages'); equal(accountOrders('TEACHER'), null);
console.log(JSON.stringify({ passed: checks, networkCalls: 0, personalData: false }));
